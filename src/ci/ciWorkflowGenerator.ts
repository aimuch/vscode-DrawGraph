// Pure generator for Diagrams-as-Code CI workflow (`.github/workflows/drawgraph-check.yml`)
// and its zero-dependency Node validation script (`.github/scripts/drawgraph-ci-check.mjs`).

export function buildDrawGraphCiWorkflowYaml(): string {
  return `name: DrawGraph Diagram Check

on:
  pull_request:
    paths:
      - '**/*.mmd'
      - '**/*.mermaid'
      - '**/*.puml'
      - '**/*.plantuml'
      - '**/*.dot'
      - '**/*.gv'
      - '**/*.d2'
      - '**/*.wavedrom'
      - '**/*.drawio'
      - '**/*.drawio.svg'
      - '**/*.md'
  workflow_dispatch:

jobs:
  validate-diagrams:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout repository
        uses: actions/checkout@v4

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: '20'

      - name: Validate diagram syntax & broken code links
        run: node .github/scripts/drawgraph-ci-check.mjs
`;
}

export function buildDrawGraphCiScript(): string {
  return `#!/usr/bin/env node
// Zero-dependency Diagrams-as-Code CI validator generated by DrawGraph.
// Checks Mermaid, PlantUML, DOT, D2, and WaveDrom syntax + broken relative file links.

import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { dirname, extname, join, resolve } from 'node:path';

const IGNORE_DIRS = new Set(['node_modules', '.git', 'dist', 'out', 'build', '.vscode-test']);
const errors = [];

function walk(dir) {
  for (const entry of readdirSync(dir)) {
    if (IGNORE_DIRS.has(entry)) continue;
    const full = join(dir, entry);
    const st = statSync(full);
    if (st.isDirectory()) {
      walk(full);
    } else {
      checkFile(full);
    }
  }
}

function checkFile(filePath) {
  const ext = extname(filePath).toLowerCase();
  if (!['.mmd', '.mermaid', '.puml', '.plantuml', '.dot', '.gv', '.d2', '.wavedrom'].includes(ext)) {
    return;
  }
  const text = readFileSync(filePath, 'utf8');
  if (!text.trim()) return;

  if (ext === '.mmd' || ext === '.mermaid') {
    const subCount = (text.match(/^\\s*subgraph\\b/gm) || []).length;
    const endCount = (text.match(/^\\s*end\\s*$/gm) || []).length;
    if (subCount > endCount) {
      errors.push(\`\${filePath}: Unclosed Mermaid subgraph block (\${subCount} subgraph vs \${endCount} end)\`);
    }
  } else if (ext === '.puml' || ext === '.plantuml') {
    const starts = (text.match(/^\\s*@start\\w+/gm) || []).length;
    const ends = (text.match(/^\\s*@end\\w+/gm) || []).length;
    if (starts !== ends) {
      errors.push(\`\${filePath}: Mismatched PlantUML @start/@end blocks (\${starts} vs \${ends})\`);
    }
  } else if (ext === '.dot' || ext === '.gv' || ext === '.d2') {
    const clean = text
      .split(/\\r?\\n/)
      .map((ln) => ln.replace(/"(?:\\\\.|[^"\\\\])*"|'(?:\\\\.|[^'\\\\])*'/g, '""').replace(/(?:\\/\\/|#).*$/, ''))
      .join('\\n');
    const opens = (clean.match(/\\{/g) || []).length;
    const closes = (clean.match(/\\}/g) || []).length;
    if (opens !== closes) {
      errors.push(\`\${filePath}: Unbalanced braces ({ = \${opens}, } = \${closes})\`);
    }
  } else if (ext === '.wavedrom') {
    try {
      JSON.parse(text);
    } catch {
      if (!/\\b(?:signal|reg)\\s*:/.test(text)) {
        errors.push(\`\${filePath}: Invalid WaveDrom structure (missing signal/reg)\`);
      }
    }
  }

  // Check click/include relative file links
  const linkRe = /(?:click\\s+\\S+\\s+"([^"]+)"|!include\\s+([^\\s<][^\\s]*))/g;
  let m;
  while ((m = linkRe.exec(text)) !== null) {
    const raw = (m[1] || m[2] || '').trim();
    if (!raw || /^(?:https?:|mailto:|#)/i.test(raw)) continue;
    const clean = raw.replace(/[:#].*$/, '');
    const relCandidate = resolve(dirname(filePath), clean);
    const rootCandidate = resolve(process.cwd(), clean);
    if (!existsSync(relCandidate) && !existsSync(rootCandidate)) {
      errors.push(\`\${filePath}: Broken relative file link "\${raw}"\`);
    }
  }
}

walk(process.cwd());

if (errors.length > 0) {
  console.error('DrawGraph CI validation failed:\\n' + errors.map((e) => '  - ' + e).join('\\n'));
  process.exit(1);
}
console.log('DrawGraph CI validation passed.');
`;
}
